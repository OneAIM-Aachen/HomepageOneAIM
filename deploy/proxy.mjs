// Builds a forwarding site for one area of the portal (no own pages):
//   node ../proxy.mjs apply    → apply address shows the portal's /apply pages at its root
//   node ../proxy.mjs network  → network address shows the portal's /network pages
// PORTAL_URL (Netlify environment variable) = address of the portal site,
// e.g. https://lambent-rolypoly-19b487.netlify.app or later https://team.one-aim.org.
// Output: out/_redirects (200 = show the page, the address stays) and out/robots.txt.
import { mkdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const area = process.argv[2];
if (area !== "apply" && area !== "network") throw new Error("Usage: node proxy.mjs apply|network");
const portal = (process.env.PORTAL_URL ?? "").replace(/\/$/, "");
if (!/^https:\/\/\S+$/.test(portal)) throw new Error("Set PORTAL_URL (https://…) in the Netlify environment variables");

const rules = [
  "# Generated by deploy/proxy.mjs – shows the portal's /" + area + " pages at this address",
  `/_astro/*     ${portal}/_astro/:splat     200`,
  `/logo.png     ${portal}/logo.png          200`,
  `/favicon.png  ${portal}/favicon.png       200`,
  `/images/*     ${portal}/images/:splat     200`,
  `/${area}      ${portal}/${area}/          200`,
  `/${area}/*    ${portal}/${area}/:splat    200`,
  `/*            ${portal}/${area}/:splat    200`,
];
const out = join(process.cwd(), "out");
mkdirSync(out, { recursive: true });
writeFileSync(join(out, "_redirects"), rules.join("\n") + "\n");
// Applications may be listed by search engines (on the live site), the network site never
writeFileSync(join(out, "robots.txt"), area === "apply" ? "User-agent: *\nAllow: /\n" : "User-agent: *\nDisallow: /\n");
console.log(`Forwarding ${area} → ${portal}/${area}`);
